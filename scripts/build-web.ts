import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dir, '..');
const publicDir = resolve(root, 'src/web/public');
for (const [entry, output] of [
  ['main', 'app'],
  ['theme', 'theme'],
  ['account', 'account'],
]) {
  const result = await Bun.build({
    entrypoints: [resolve(root, `src/web/client/${entry}.js`)],
    outdir: publicDir,
    naming: `${output}.js`,
    banner: '// Generated by bun run build:web from src/web/client/. Do not edit.',
    target: 'browser',
    format: entry === 'account' ? 'esm' : 'iife',
    minify: true,
    define: { 'process.env.NODE_ENV': JSON.stringify('production') },
  });
  if (!result.success) throw new AggregateError(result.logs, `${output} build failed`);
}
const notices = [
  ['marked', 'LICENSE'],
  ['dompurify', 'LICENSE'],
  ['@hugeicons/core-free-icons', 'LICENSE.md'],
  ['react', 'LICENSE'],
  ['react-dom', 'LICENSE'],
  ['@clerk/electron', 'LICENSE'],
  ['@clerk/react', 'LICENSE'],
  ['@clerk/shared', 'LICENSE'],
  ['@clerk/clerk-js', 'LICENSE'],
].map(
  ([name, file]) => `${name}\n${readFileSync(resolve(root, 'node_modules', name!, file!), 'utf8')}`,
);
await Bun.write(resolve(publicDir, 'THIRD_PARTY_NOTICES.txt'), notices.join('\n\n'));
